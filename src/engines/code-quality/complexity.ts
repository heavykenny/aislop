interface FunctionInfo {
	name: string;
	startLine: number;
	lineCount: number;
	maxNesting: number;
	paramCount: number;
	templateLines: number;
}
interface FunctionPattern {
	regex: RegExp;
	langFilter: string[];
}

const FUNCTION_PATTERNS: FunctionPattern[] = [
	{
		regex: /^\s*(?:export\s+)?(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)/,
		langFilter: [".js", ".ts", ".jsx", ".tsx", ".mjs", ".cjs"],
	},
	{
		regex: /^\s*(?:export\s+)?const\s+(\w+)\s*=\s*(?:async\s+)?\(([^)]*)\)\s*(?:=>|:\s*\w)/,
		langFilter: [".js", ".ts", ".jsx", ".tsx", ".mjs", ".cjs"],
	},
	{
		regex: /^\s*(?:async\s+)?def\s+(\w+)\s*\(/,
		langFilter: [".py"],
	},
	{
		regex: /^\s*func\s+(?:\([^)]*\)\s+)?(\w+)\s*\(([^)]*)\)/,
		langFilter: [".go"],
	},
	{
		regex: /^\s*fn\s+(\w+)\s*\(([^)]*)\)/,
		langFilter: [".rs"],
	},
	{
		// The (?:(?!STMT_KW)\w+\s+) part requires that the "return type" token is not a
		// statement keyword. This prevents a call expression like `return Foo(args)` or
		// `if (Foo(args))` from matching as a definition: `return` / `if` / etc. would
		// be parsed as the return type, but the negative lookahead inside the token group
		// rejects them before \w+ can consume the keyword.
		regex:
			/^\s*(?:public|private|protected)?\s*(?:static\s+)?(?:(?!(?:return|if|for|while|switch|do|else|throw|delete|new|break|continue|goto|try|catch)\b)\w+\s+)(\w+)\s*\(([^)]*)\)/,
		langFilter: [".java", ".cs", ".cpp", ".c", ".php"],
	},
	{
		// C# methods and constructors the single-token pattern above misses: any
		// run of access/async/etc. modifiers, then an arbitrary return type (which
		// may be generic/array/qualified/nullable, or absent for a constructor),
		// then the member name. A modifier is required so bare `Type name(...)`
		// calls/declarations are not matched. `[^()=;{]` stops the lazy return-type
		// run before a body brace, an expression-body `=>`, or a field initializer.
		regex:
			/^\s*(?:\[[^\]]*\]\s*)*(?:(?:public|private|protected|internal|static|async|virtual|override|sealed|abstract|extern|unsafe|new|partial|readonly)\s+)+[^()=;{]*?(\w+)\s*\(([^)]*)\)/,
		langFilter: [".cs"],
	},
];

// Extensions whose function signatures may wrap across multiple physical lines
// and so need logical-signature joining before the patterns are applied. Scoped
// to C# so Java/PHP/C-family detection stays byte-identical to the single-line path.
const MULTILINE_SIGNATURE_EXTS = new Set([".cs"]);

// A brace-language signature can span lines (wrapped parameter lists). When the
// line at `startIndex` opens more parens than it closes, join following lines
// (up to a small cap, stopping at a statement `;`) so the single-line
// FUNCTION_PATTERNS can see the whole `name(...)` on one logical line. Newlines
// become spaces; the reported start line stays `startIndex`.
const logicalSignatureLine = (lines: string[], startIndex: number): string => {
	const first = lines[startIndex];
	let depth = 0;
	let sawOpen = false;
	for (const ch of first) {
		if (ch === "(") {
			depth++;
			sawOpen = true;
		} else if (ch === ")") depth--;
	}
	if (!sawOpen || depth <= 0) return first;

	let joined = first;
	for (let j = startIndex + 1; j < lines.length && j < startIndex + 12; j++) {
		const line = lines[j];
		joined += ` ${line}`;
		for (const ch of line) {
			if (ch === "(") depth++;
			else if (ch === ")") depth--;
		}
		if (depth <= 0) break;
		if (line.includes(";")) break;
	}
	return joined;
};

// Count top-level parameters, ignoring commas nested inside generic type
// arguments (`IReadOnlyDictionary<string, int>`), tuples (`(int, int)`), arrays,
// or default initializers. A plain `.split(",")` overcounts C# signatures
// whose parameter types carry commas - a 5-parameter constructor of
// dictionary-typed arguments would be misreported as 9. Bracket depth floors at
// zero so an unmatched closer (a stray relational `>` in a default expression)
// cannot drive the depth negative and leak inner commas back to the top level.
const countParams = (parameterList: string): number => {
	const trimmed = parameterList.trim();
	if (!trimmed) return 0;
	let depth = 0;
	let count = 1;
	for (const ch of trimmed) {
		if (ch === "(" || ch === "[" || ch === "{" || ch === "<") {
			depth++;
		} else if (ch === ")" || ch === "]" || ch === "}" || ch === ">") {
			depth = Math.max(0, depth - 1);
		} else if (ch === "," && depth === 0) {
			count++;
		}
	}
	return count;
};

const matchFunctionOnLine = (
	line: string,
	ext: string,
): { name: string; params: string; patternIndex: number } | null => {
	for (let i = 0; i < FUNCTION_PATTERNS.length; i++) {
		const pattern = FUNCTION_PATTERNS[i];
		if (!pattern.langFilter.includes(ext)) continue;
		const match = line.match(pattern.regex);
		if (match) return { name: match[1], params: match[2] ?? "", patternIndex: i };
	}
	return null;
};

const isDataFile = (content: string): boolean => {
	const lines = content.split("\n");
	const nonEmpty = lines.filter((l) => l.trim().length > 0);
	if (nonEmpty.length === 0) return false;
	const dataLinePattern = /^\s*[{}[\]"']/;
	const dataLines = nonEmpty.filter((l) => dataLinePattern.test(l));
	return dataLines.length / nonEmpty.length > 0.8;
};

const TEST_PATH_RE = /(?:^|\/)(?:tests?|spec|specs|__tests__|__spec__|src\/test)\//i;
const TEST_BASENAME_RE =
	/(?:^|[/.])(?:test_[\w-]+\.(?:py|rb)|[\w-]+_(?:test|spec)\.(?:py|rb|go|rs)|[\w-]+\.(?:test|spec)\.(?:[jt]sx?|mjs|cjs)|conftest\.py|[A-Z]\w*Tests?\.(?:java|cs|php))$/;

const MIGRATION_PATH_RE = /(?:^|\/)(?:migrations?|migrate|prisma\/migrations|db\/migrate)\//i;

const FIXTURE_PATH_RE =
	/(?:^|\/)(?:__fixtures__|__snapshots__|__mocks__|fixtures?|snapshots?|seeds?|stubs?)\//i;

const GENERATED_PATH_RE =
	/(?:^|\/)(?:generated|gen|build|dist|out|target|coverage|node_modules|vendor|\.next|\.nuxt|\.svelte-kit)\//i;

const isExemptFromComplexity = (relativePath: string): boolean =>
	TEST_PATH_RE.test(relativePath) ||
	TEST_BASENAME_RE.test(relativePath) ||
	MIGRATION_PATH_RE.test(relativePath) ||
	FIXTURE_PATH_RE.test(relativePath) ||
	GENERATED_PATH_RE.test(relativePath);

export const analyzeFunctions = (content: string, ext: string): FunctionInfo[] => {
	const lines = content.split("\n");
	// String and comment bodies blanked (newlines preserved, so line indices still
	// align with `lines`) so the brace matcher never counts a `{`/`}` inside a
	// literal or comment as a block delimiter.
	const maskedLines = maskStringsAndComments(content, ext).split("\n");
	const functions: FunctionInfo[] = [];

	for (let i = 0; i < lines.length; i++) {
		// For C# match against the masked (string/comment-blanked) source so a
		// wrapped signature is joined on balanced parens and literals never skew it.
		const matchLine = MULTILINE_SIGNATURE_EXTS.has(ext)
			? logicalSignatureLine(maskedLines, i)
			: lines[i];
		const fnMatch = matchFunctionOnLine(matchLine, ext);
		if (!fnMatch) continue;

		const isPython = fnMatch.patternIndex === 2;

		if (fnMatch.patternIndex === 1 && !isBlockArrow(maskedLines, i)) {
			continue;
		}

		const { endLine, maxNesting } = findFunctionEnd(maskedLines, i, isPython);
		// endLine < 0 marks a non-definition (prototype, static-call statement) that
		// matched a pattern by shape but has no body - skip it entirely.
		if (endLine < 0) continue;
		let templateLines: number;
		let paramCount: number;
		if (isPython) {
			const sig = extractPythonSignature(lines, i);
			const codeLines = countPythonBodyCodeLines(lines, sig.sigEndIndex, endLine);
			templateLines = endLine - i + 1 - codeLines;
			paramCount = countPythonParams(sig.params);
		} else {
			templateLines = countTemplateLines(lines.slice(i + 1, endLine));
			paramCount = countParams(fnMatch.params);
		}

		functions.push({
			name: fnMatch.name,
			startLine: i + 1,
			lineCount: endLine - i + 1,
			maxNesting,
			paramCount,
			templateLines,
		});
	}

	return functions;
};

interface QualityLimits {
	maxFunctionLoc: number;
	maxFileLoc: number;
	maxNesting: number;
	maxParams: number;
}

const FILE_LOC_MULTIPLIERS: Record<string, number> = {
	".tsx": 1.5,
	".jsx": 1.5,
	".rs": 2.5,
	".go": 1.5,
};

const DECLARATION_FILE_RE = /\.d\.ts$/i;

const GENERIC_FILE_TOO_LARGE_HELP = "Consider splitting this file into smaller modules";
// C# has a language-native remediation: partial classes split a type across
// files with no API or linkage cost, so point C# users at it directly.
const CSHARP_FILE_TOO_LARGE_HELP =
	"Consider splitting this file into partial class files or smaller modules";

const fileTooLargeHelp = (ext: string): string =>
	ext === ".cs" ? CSHARP_FILE_TOO_LARGE_HELP : GENERIC_FILE_TOO_LARGE_HELP;

const fileLocBudget = (ext: string, relativePath: string, base: number): number => {
	if (DECLARATION_FILE_RE.test(relativePath)) return Number.POSITIVE_INFINITY;
	const multiplier = FILE_LOC_MULTIPLIERS[ext] ?? 1;
	return Math.ceil(base * multiplier);
};

const checkFileDiagnostics = (
	relativePath: string,
	content: string,
	limits: QualityLimits,
): Diagnostic[] => {
	const results: Diagnostic[] = [];
	const lineCount = content.split("\n").length;
	const ext = path.extname(relativePath).toLowerCase();

	if (isDataFile(content)) return results;

	const configuredMax = fileLocBudget(ext, relativePath, limits.maxFileLoc);
	if (!Number.isFinite(configuredMax)) return results;
	const triggerAt = Math.ceil(configuredMax * 1.1);

	if (lineCount > triggerAt) {
		results.push({
			filePath: relativePath,
			engine: "code-quality",
			rule: "complexity/file-too-large",
			severity: "warning",
			message: `File too large (max: ${configuredMax})`,
			help: fileTooLargeHelp(ext),
			line: 0,
			column: 0,
			category: "Complexity",
			fixable: false,
			detail: `${lineCount} lines`,
		});
	}

	return results;
};

const JSX_EXTENSIONS = new Set([".tsx", ".jsx"]);
const isComponentFunction = (name: string, ext: string): boolean =>
	JSX_EXTENSIONS.has(ext) && /^[A-Z]/.test(name);

const functionLocBudget = (fn: FunctionInfo, ext: string, base: number): number => {
	if (isComponentFunction(fn.name, ext)) return Math.ceil(base * 2.0);
	if (ext === ".rs") return Math.ceil(base * 1.5);
	return base;
};

const checkFunctionDiagnostics = (
	relativePath: string,
	fn: FunctionInfo,
	limits: QualityLimits,
	ext: string,
): Diagnostic[] => {
	const results: Diagnostic[] = [];

	const fnMax = functionLocBudget(fn, ext, limits.maxFunctionLoc);
	const effectiveLineCount = fn.lineCount - fn.templateLines;
	if (effectiveLineCount > Math.ceil(fnMax * 1.1)) {
		results.push({
			filePath: relativePath,
			engine: "code-quality",
			rule: "complexity/function-too-long",
			severity: "warning",
			message: `Function too long (max: ${fnMax})`,
			help: "Consider breaking this function into smaller pieces",
			line: fn.startLine,
			column: 0,
			category: "Complexity",
			fixable: false,
			detail: `${fn.name} · ${fn.lineCount} lines`,
		});
	}

	if (fn.maxNesting > limits.maxNesting) {
		results.push({
			filePath: relativePath,
			engine: "code-quality",
			rule: "complexity/deep-nesting",
			severity: "warning",
			message: `Function nested too deeply (max: ${limits.maxNesting})`,
			help: "Consider using early returns or extracting nested logic",
			line: fn.startLine,
			column: 0,
			category: "Complexity",
			fixable: false,
			detail: `${fn.name} · depth ${fn.maxNesting}`,
		});
	}

	if (fn.paramCount > limits.maxParams) {
		results.push({
			filePath: relativePath,
			engine: "code-quality",
			rule: "complexity/too-many-params",
			severity: "warning",
			message: `Function has too many parameters (max: ${limits.maxParams})`,
			help: "Consider using an options object parameter",
			line: fn.startLine,
			column: 0,
			category: "Complexity",
			fixable: false,
			detail: `${fn.name} · ${fn.paramCount} params`,
		});
	}

	return results;
};

const checkFileComplexity = (
	filePath: string,
	rootDirectory: string,
	limits: QualityLimits,
): Diagnostic[] => {
	const relativePath = relativePosix(rootDirectory, filePath);
	if (isExemptFromComplexity(relativePath)) return [];

	let content: string;
	try {
		content = fs.readFileSync(filePath, "utf-8");
	} catch {
		return [];
	}

	const ext = path.extname(filePath).toLowerCase();
	const diagnostics = checkFileDiagnostics(relativePath, content, limits);

	for (const fn of analyzeFunctions(content, ext)) {
		diagnostics.push(...checkFunctionDiagnostics(relativePath, fn, limits, ext));
	}

	return diagnostics;
};

export const checkComplexity = async (context: EngineContext): Promise<Diagnostic[]> => {
	const files = getSourceFiles(context);
	const limits: QualityLimits = context.config.quality;
	const diagnostics: Diagnostic[] = [];

	for (const filePath of files) {
		if (isAutoGenerated(filePath)) continue;
		diagnostics.push(...checkFileComplexity(filePath, context.rootDirectory, limits));
	}

	return diagnostics;
};
